import { dirname, join, resolve, win32 as win32Path } from "node:path";

export const ALU_DOCK_UNIT_NAME = "alu-dock.service";
export const ALU_DOCK_MANAGED_ENV = "ALU_DOCK_MANAGED";
export const ALU_DOCK_GENERATED_MARKER = "# Generated by Alu Dock local install; do not edit in place.";

export interface LocalInstallLayout {
  root: string;
  packageDirectory: string;
  cliPath: string;
  packageExecutable: string;
  userExecutable: string;
  unitFile: string;
  windowsHostLogPath?: string;
}

export interface AluDockUnitOptions {
  nodePath: string;
  cliPath: string;
  homePath: string;
}

export interface LocalInstallLayoutOptions {
  platform?: NodeJS.Platform;
  localAppData?: string;
}

export function localInstallLayout(home: string, installRoot?: string, options: LocalInstallLayoutOptions = {}): LocalInstallLayout {
  const platform = options.platform ?? process.platform;
  if (platform === "win32") {
    const resolvedHome = win32Path.resolve(home);
    const localAppData = win32Path.resolve(options.localAppData ?? win32Path.join(resolvedHome, "AppData", "Local"));
    const root = win32Path.resolve(installRoot ?? win32Path.join(localAppData, "AluDock"));
    const packageDirectory = win32Path.join(root, "dock");
    const packageExecutable = win32Path.join(root, "aludock.cmd");
    const cliPath = win32Path.join(packageDirectory, "dist", "src", "cli.js");
    return {
      root,
      packageDirectory,
      cliPath,
      packageExecutable,
      userExecutable: packageExecutable,
      unitFile: cliPath,
      windowsHostLogPath: win32Path.join(localAppData, "Alu Dock", "logs", "host.log"),
    };
  }
  const resolvedHome = resolve(home);
  const root = resolve(installRoot ?? join(resolvedHome, ".local", "share", "alu-dock"));
  const packageDirectory = join(root, "dock");
  return {
    root,
    packageDirectory,
    cliPath: join(packageDirectory, "dist", "src", "cli.js"),
    packageExecutable: join(packageDirectory, "dist", "src", "cli.js"),
    userExecutable: join(resolvedHome, ".local", "bin", "aludock"),
    unitFile: join(resolvedHome, ".config", "systemd", "user", ALU_DOCK_UNIT_NAME),
  };
}

export function isAluDockGeneratedContent(content: string): boolean {
  return (
    content.startsWith(`${ALU_DOCK_GENERATED_MARKER}\n`) ||
    content.startsWith(`#!/bin/sh\n${ALU_DOCK_GENERATED_MARKER}\n`)
  );
}

export function renderAluDockUnit(options: AluDockUnitOptions): string {
  assertSafeAbsolutePath(options.nodePath, "Node");
  assertSafeAbsolutePath(options.cliPath, "CLI");
  assertSafeAbsolutePath(options.homePath, "Home");
  const executablePath = managedExecutablePath(options.nodePath, options.homePath);
  const homePath = resolve(options.homePath);
  return `${ALU_DOCK_GENERATED_MARKER}
[Unit]
Description=Alu Dock managed Pi SDK host
After=default.target
StartLimitIntervalSec=30
StartLimitBurst=5

[Service]
Type=exec
ExecStart=${systemdQuote(resolve(options.nodePath))} ${systemdQuote(resolve(options.cliPath))} serve --managed
Environment=${ALU_DOCK_MANAGED_ENV}=1
Environment=ALU_DOCK_SOCKET=
Environment=NODE_ENV=production
Environment=${systemdQuote(`HOME=${homePath}`)}
Environment=${systemdQuote(`PATH=${executablePath}`)}
Restart=on-failure
RestartSec=2s
TimeoutStartSec=15s
TimeoutStopSec=15s
KillSignal=SIGTERM
KillMode=mixed
# 2026-09-30: a 66 GiB test process in one Worker was OOM-killed and systemd's
# default OOMPolicy=stop then stopped the whole Dock. Keep Host and the other
# Works running; the kernel only kills the runaway process. The hard total,
# with swap excluded, ends a runaway before the machine starts thrashing.
OOMPolicy=continue
MemoryMax=20G
MemorySwapMax=0
RuntimeDirectory=alu-dock
RuntimeDirectoryMode=0700
StateDirectory=alu-dock
StateDirectoryMode=0700
WorkingDirectory=%h
UMask=0077
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=default.target
`;
}

export interface LocalInstallInstanceState {
  id: string;
  name?: string;
  lifecycle: "active" | "stopping" | "stopped" | "host_lost" | "runtime_error";
  execution: "idle" | "running" | "failed" | "unavailable";
  compacting?: boolean;
  pending?: { total: number };
  activeInteraction?: unknown;
  activeCommandId?: string;
}

export interface LocalInstallOptions {
  replaceActive: boolean;
}

export function parseLocalInstallArguments(args: readonly string[]): LocalInstallOptions {
  let replaceActive = false;
  for (const argument of args) {
    if (argument === "--replace-active") replaceActive = true;
    else throw new Error(`Unknown local install option: ${argument}. Usage: npm run install:local -- [--replace-active]`);
  }
  return { replaceActive };
}

export function localInstallInspectionMayAssumeHostAbsent(hostReached: boolean, errorCode: string): boolean {
  return !hostReached && errorCode === "connection_error";
}

export function localInstallBlockingInstances(instances: readonly LocalInstallInstanceState[]): LocalInstallInstanceState[] {
  return instances.filter((instance) => {
    if (instance.lifecycle === "stopping") return true;
    if (instance.lifecycle !== "active") return false;
    return instance.execution === "running"
      || instance.execution === "unavailable"
      || instance.compacting === true
      || (instance.pending?.total ?? 0) > 0
      || instance.activeInteraction !== undefined
      || instance.activeCommandId !== undefined;
  });
}

export function assertLocalInstallAllowed(instances: readonly LocalInstallInstanceState[], replaceActive = false): void {
  const blocking = localInstallBlockingInstances(instances);
  if (blocking.length === 0 || replaceActive) return;
  const labels = blocking.map((instance) => {
    const label = safeLocalInstallName(instance.name);
    return `${label} (${localInstallBlockingReason(instance)})`;
  });
  throw new Error(
    `Update paused because ${blocking.length} work item${blocking.length === 1 ? " still needs" : "s still need"} Alu Dock: ${labels.join(", ")}.\n`
    + "Finish or stop the listed work before updating. To replace Alu Dock anyway, run:\n"
    + "  npm run install:local -- --replace-active\n"
    + "Replacing Alu Dock interrupts current responses, waiting messages, and tool actions in progress.",
  );
}

function safeLocalInstallName(name: string | undefined): string {
  return name
    ?.replace(/[\u0000-\u001f\u007f-\u009f]/gu, " ")
    .replace(/\s+/gu, " ")
    .trim() || "Unnamed work";
}

function localInstallBlockingReason(instance: LocalInstallInstanceState): string {
  if (instance.compacting) return "preparing its conversation";
  if (instance.lifecycle === "stopping") return "finishing";
  if (instance.execution === "running") return "responding";
  if (instance.execution === "unavailable") return "waiting to reconnect";
  if ((instance.pending?.total ?? 0) > 0) return "has waiting messages";
  if (instance.activeInteraction !== undefined) return "waiting for an answer";
  if (instance.activeCommandId !== undefined) return "finishing a command";
  return "still active";
}

function managedExecutablePath(nodePath: string, homePath: string): string {
  const home = resolve(homePath);
  const entries = [
    dirname(resolve(nodePath)),
    join(home, ".local", "bin"),
    "/usr/local/sbin",
    "/usr/local/bin",
    "/usr/sbin",
    "/usr/bin",
    "/sbin",
    "/bin",
  ];
  const unique = [...new Set(entries)];
  for (const entry of unique) {
    assertSafeAbsolutePath(entry, "Executable PATH entry");
    if (entry.includes(":")) throw new Error("Executable PATH entries cannot contain colons");
  }
  return unique.join(":");
}

function assertSafeAbsolutePath(path: string, label: string): void {
  if (!path.startsWith("/") || path.includes("\n") || path.includes("\r") || path.includes("\0")) throw new Error(`${label} path must be a safe absolute path`);
}

function systemdQuote(value: string): string {
  return `"${value.replaceAll("%", "%%").replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}
