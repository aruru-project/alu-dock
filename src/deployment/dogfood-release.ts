import { dirname, join, resolve } from "node:path";

export const DOGFOOD_UNIT_NAME = "alu-dock.service";
export const DOGFOOD_MANAGED_ENV = "ALU_DOCK_MANAGED";
export const DOGFOOD_GENERATED_MARKER = "# Generated by Alu Dock dogfood deploy; do not edit in place.";

export interface DogfoodReleaseLayout {
  root: string;
  releases: string;
  receipts: string;
  current: string;
  launcher: string;
  userLauncher: string;
  unitFile: string;
}

export interface DogfoodUnitOptions {
  nodePath: string;
  cliPath: string;
  homePath: string;
}

export function dogfoodReleaseLayout(home: string, releaseRoot = join(home, "release", "alu-dock")): DogfoodReleaseLayout {
  const root = resolve(releaseRoot);
  return {
    root,
    releases: join(root, "releases"),
    receipts: join(root, "receipts"),
    current: join(root, "current"),
    launcher: join(root, "bin", "alu-dock"),
    userLauncher: join(resolve(home), ".local", "bin", "alu-dock"),
    unitFile: join(resolve(home), ".config", "systemd", "user", DOGFOOD_UNIT_NAME),
  };
}

export function renderDogfoodLauncher(nodePath: string, cliPath: string): string {
  assertSafeAbsolutePath(nodePath, "Node");
  assertSafeAbsolutePath(cliPath, "CLI");
  return `#!/bin/sh\n${DOGFOOD_GENERATED_MARKER}\nexport ${DOGFOOD_MANAGED_ENV}=1\nexec ${shellQuote(nodePath)} ${shellQuote(cliPath)} "$@"\n`;
}

export function renderReleasedHostInspectionScript(): string {
  return [
    "import { pathToFileURL } from 'node:url';",
    "const { DockClient } = await import(pathToFileURL(process.argv[1]).href);",
    "const client = new DockClient({ socketPath: process.argv[2], timeoutMs: 500 });",
    "const ping = await client.ping();",
    "const instances = await client.list();",
    "const activeInstances = instances.filter((item) => item.lifecycle === 'active' || item.lifecycle === 'stopping').length;",
    "process.stdout.write(JSON.stringify({ pid: ping.pid, hostEpoch: ping.hostEpoch, activeInstances }));",
  ].join("");
}

export function renderDogfoodUnit(options: DogfoodUnitOptions): string {
  assertSafeAbsolutePath(options.nodePath, "Node");
  assertSafeAbsolutePath(options.cliPath, "CLI");
  assertSafeAbsolutePath(options.homePath, "Home");
  const executablePath = managedExecutablePath(options.nodePath, options.homePath);
  return `${DOGFOOD_GENERATED_MARKER}
[Unit]
Description=Alu Dock managed Pi SDK host
After=default.target
StartLimitIntervalSec=30
StartLimitBurst=5

[Service]
Type=exec
ExecStart=${systemdQuote(options.nodePath)} ${systemdQuote(options.cliPath)} serve --managed
Environment=${DOGFOOD_MANAGED_ENV}=1
Environment=ALU_DOCK_SOCKET=
Environment=NODE_ENV=production
Environment=${systemdQuote(`PATH=${executablePath}`)}
Restart=on-failure
RestartSec=2s
TimeoutStartSec=15s
TimeoutStopSec=15s
KillSignal=SIGTERM
KillMode=mixed
RuntimeDirectory=alu-dock
RuntimeDirectoryMode=0700
StateDirectory=alu-dock
StateDirectoryMode=0700
WorkingDirectory=%h
UMask=0077
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=default.target
`;
}

export function releaseId(timestamp: Date, commit: string): string {
  if (!/^[0-9a-f]{40}$/u.test(commit)) throw new Error("Release commit must be a full lowercase Git SHA");
  if (!Number.isFinite(timestamp.getTime())) throw new Error("Release timestamp must be valid");
  const compactTime = timestamp.toISOString().replace(/[-:]/gu, "").replace(/\.\d{3}Z$/u, "Z");
  return `${compactTime}-${commit.slice(0, 12)}`;
}

function managedExecutablePath(nodePath: string, homePath: string): string {
  const entries = [
    dirname(resolve(nodePath)),
    join(resolve(homePath), ".local", "bin"),
    "/usr/local/sbin",
    "/usr/local/bin",
    "/usr/sbin",
    "/usr/bin",
    "/sbin",
    "/bin",
  ];
  const unique = [...new Set(entries)];
  for (const entry of unique) {
    assertSafeAbsolutePath(entry, "Executable PATH entry");
    if (entry.includes(":")) throw new Error("Executable PATH entries cannot contain colons");
  }
  return unique.join(":");
}

function assertSafeAbsolutePath(path: string, label: string): void {
  if (!path.startsWith("/") || path.includes("\n") || path.includes("\r") || path.includes("\0")) throw new Error(`${label} path must be a safe absolute path`);
}

function shellQuote(value: string): string {
  return `'${value.replaceAll("'", `'"'"'`)}'`;
}

function systemdQuote(value: string): string {
  return `"${value.replaceAll("%", "%%").replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}
