export function parseAthenaPendingRelease(value: unknown): AthenaPendingRelease {
  if (value === null || typeof value !== "object" || Array.isArray(value)) throw new Error("Pending athena release must be an object");
  const record = value as Record<string, unknown>;
  const allowed = new Set(["schemaVersion", "releaseId", "commit", "stagedAt", "projectCwd", "previousRelease"]);
  if (Object.keys(record).some((key) => !allowed.has(key))) throw new Error("Pending athena release contains unknown fields");
  if (record.schemaVersion !== 1) throw new Error("Pending athena release schema is unsupported");
  if (typeof record.releaseId !== "string" || !/^\d{8}T\d{6}Z-[0-9a-f]{12}$/u.test(record.releaseId)) throw new Error("Pending athena release ID is invalid");
  if (typeof record.commit !== "string" || !/^[0-9a-f]{40}$/u.test(record.commit)) throw new Error("Pending athena commit is invalid");
  if (typeof record.stagedAt !== "string" || !Number.isFinite(Date.parse(record.stagedAt))) throw new Error("Pending athena stagedAt is invalid");
  if (typeof record.projectCwd !== "string" || !record.projectCwd.startsWith("/")) throw new Error("Pending athena project cwd is invalid");
  if (record.previousRelease !== undefined && (typeof record.previousRelease !== "string" || !record.previousRelease.startsWith("/"))) throw new Error("Pending athena previous release is invalid");
  return {
    schemaVersion: 1,
    releaseId: record.releaseId,
    commit: record.commit,
    stagedAt: record.stagedAt,
    projectCwd: record.projectCwd,
    ...(record.previousRelease === undefined ? {} : { previousRelease: record.previousRelease }),
  };
}

export function parseAthenaSystemdUnitEvidence(output: string): AthenaSystemdUnitEvidence {
  const fields = new Map<string, string>();
  for (const line of output.split("\n")) {
    const separator = line.indexOf("=");
    if (separator > 0) fields.set(line.slice(0, separator), line.slice(separator + 1));
  }
  const loadState = fields.get("LoadState");
  const activeState = fields.get("ActiveState");
  const unitFileState = fields.get("UnitFileState");
  const mainPid = Number(fields.get("MainPID"));
  if (!Number.isSafeInteger(mainPid) || mainPid < 0 || loadState === undefined || activeState === undefined || unitFileState === undefined) {
    throw new Error("systemd returned incomplete Athena unit evidence");
  }
  if (loadState === "not-found") {
    if (activeState !== "inactive" || mainPid !== 0 || unitFileState !== "") throw new Error("systemd returned inconsistent evidence for an absent Athena unit");
    return { active: false, enabled: false, mainPid: 0 };
  }
  if (loadState !== "loaded") throw new Error(`Athena unit has unsupported LoadState=${loadState}`);
  if (!["active", "inactive", "failed"].includes(activeState)) throw new Error(`Athena unit is transitioning (${activeState}); retry after it settles`);
  if (activeState === "active" && mainPid <= 1) throw new Error("Active Athena unit has no safe MainPID");
  if (activeState !== "active" && mainPid !== 0) throw new Error("Inactive Athena unit still reports a MainPID");
  if (unitFileState !== "enabled" && unitFileState !== "disabled") throw new Error(`Athena unit has unsupported UnitFileState=${unitFileState}`);
  return { active: activeState === "active", enabled: unitFileState === "enabled", mainPid };
}

export function planAthenaLegacyLauncherCleanup(
  launcher: "absent" | "generated" | "unowned",
  userLauncher: "absent" | "legacy_target" | "other",
): { removeLauncher: boolean; removeUserLauncher: boolean } {
  return {
    removeLauncher: launcher === "generated",
    removeUserLauncher: userLauncher === "legacy_target" && launcher !== "unowned",
  };
}

export function athenaHostAbsenceIsConfirmed(unitActive: boolean, mainPid: number, socketPresent: boolean): boolean {
  if (!Number.isSafeInteger(mainPid) || mainPid < 0) throw new Error("Athena MainPID evidence is invalid");
  return !unitActive && mainPid === 0 && !socketPresent;
}

export function assertAthenaHostReplacementAllowed(activeInstances: number, allowActive: boolean): void {
  if (!Number.isSafeInteger(activeInstances) || activeInstances < 0) throw new Error("Athena active instance count is invalid");
  if (activeInstances > 0 && !allowActive) {
    throw new Error(`Athena update refused: current Host has ${activeInstances} active instance(s); stop them first or pass --allow-active explicitly`);
  }
}

export function planAthenaRollback(
  serviceWasActive: boolean,
  serviceWasEnabled: boolean,
  previousReleaseExists: boolean,
): {
  current: "switch_previous" | "remove_current";
  service: "start" | "leave_stopped";
  enablement: "enable" | "disable";
} {
  return {
    current: previousReleaseExists ? "switch_previous" : "remove_current",
    service: serviceWasActive ? "start" : "leave_stopped",
    enablement: serviceWasEnabled ? "enable" : "disable",
  };
}

export function assertAthenaJournalClean(output: string): void {
  const severe = output.trim();
  if (severe.length > 0) throw new Error(`Athena journal gate found error-priority entries: ${severe.slice(-4_000)}`);
}

export function releaseId(timestamp: Date, commit: string): string {
  if (!/^[0-9a-f]{40}$/u.test(commit)) throw new Error("Release commit must be a full lowercase Git SHA");
  if (!Number.isFinite(timestamp.getTime())) throw new Error("Release timestamp must be valid");
  const compactTime = timestamp.toISOString().replace(/[-:]/gu, "").replace(/\.\d{3}Z$/u, "Z");
  return `${compactTime}-${commit.slice(0, 12)}`;
}

function managedExecutablePath(nodePath: string, homePath: string): string {
  const entries = [
    dirname(resolve(nodePath)),
    join(resolve(homePath), ".local", "bin"),
    "/usr/local/sbin",
    "/usr/local/bin",
    "/usr/sbin",
    "/usr/bin",
    "/sbin",
    "/bin",
  ];
  const unique = [...new Set(entries)];
  for (const entry of unique) {
    assertSafeAbsolutePath(entry, "Executable PATH entry");
    if (entry.includes(":")) throw new Error("Executable PATH entries cannot contain colons");
  }
  return unique.join(":");
}

function assertSafeAbsolutePath(path: string, label: string): void {
  if (!path.startsWith("/") || path.includes("\n") || path.includes("\r") || path.includes("\0")) throw new Error(`${label} path must be a safe absolute path`);
}

function shellQuote(value: string): string {
  return `'${value.replaceAll("'", `'"'"'`)}'`;
}

function systemdQuote(value: string): string {
  return `"${value.replaceAll("%", "%%").replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}
