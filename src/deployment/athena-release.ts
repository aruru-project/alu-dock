import { dirname, join, resolve } from "node:path";

export const ATHENA_UNIT_NAME = "alu-dock.service";
export const ATHENA_MANAGED_ENV = "ALU_DOCK_MANAGED";
export const ATHENA_GENERATED_MARKER = "# Generated by Alu Dock Athena deploy; do not edit in place.";
const LEGACY_GENERATED_MARKER = "# Generated by Alu Dock dogfood deploy; do not edit in place.";

export interface AthenaReleaseLayout {
  root: string;
  releases: string;
  receipts: string;
  current: string;
  pending: string;
  launcher: string;
  userLauncher: string;
  legacyLauncher: string;
  legacyUserLauncher: string;
  unitFile: string;
}

export interface AthenaSystemdUnitEvidence {
  active: boolean;
  enabled: boolean;
  mainPid: number;
}

export interface AthenaPendingRelease {
  schemaVersion: 1;
  releaseId: string;
  commit: string;
  stagedAt: string;
  projectCwd: string;
  previousRelease?: string;
}

export interface AthenaUnitOptions {
  nodePath: string;
  cliPath: string;
  homePath: string;
}

export function athenaReleaseLayout(home: string, releaseRoot = join(home, "release", "alu-dock")): AthenaReleaseLayout {
  const root = resolve(releaseRoot);
  return {
    root,
    releases: join(root, "releases"),
    receipts: join(root, "receipts"),
    current: join(root, "current"),
    pending: join(root, "pending.json"),
    launcher: join(root, "bin", "aludock"),
    userLauncher: join(resolve(home), ".local", "bin", "aludock"),
    legacyLauncher: join(root, "bin", "alu-dock"),
    legacyUserLauncher: join(resolve(home), ".local", "bin", "alu-dock"),
    unitFile: join(resolve(home), ".config", "systemd", "user", ATHENA_UNIT_NAME),
  };
}

export function isAthenaGeneratedContent(content: string): boolean {
  return content.startsWith(`${ATHENA_GENERATED_MARKER}\n`)
    || content.startsWith(`#!/bin/sh\n${ATHENA_GENERATED_MARKER}\n`)
    || content.startsWith(`${LEGACY_GENERATED_MARKER}\n`)
    || content.startsWith(`#!/bin/sh\n${LEGACY_GENERATED_MARKER}\n`);
}

export function renderAthenaLauncher(nodePath: string, cliPath: string): string {
  assertSafeAbsolutePath(nodePath, "Node");
  assertSafeAbsolutePath(cliPath, "CLI");
  return `#!/bin/sh\n${ATHENA_GENERATED_MARKER}\nexport ${ATHENA_MANAGED_ENV}=1\nexec ${shellQuote(nodePath)} ${shellQuote(cliPath)} "$@"\n`;
}

export function renderReleasedHostInspectionScript(): string {
  return [
    "import { pathToFileURL } from 'node:url';",
    "const { DockClient } = await import(pathToFileURL(process.argv[1]).href);",
    "const client = new DockClient({ socketPath: process.argv[2], timeoutMs: 500 });",
    "const ping = await client.ping();",
    "const instances = await client.list();",
    "const activeInstances = instances.filter((item) => item.lifecycle === 'active' || item.lifecycle === 'stopping').length;",
    "process.stdout.write(JSON.stringify({ pid: ping.pid, hostEpoch: ping.hostEpoch, activeInstances }));",
  ].join("");
}

