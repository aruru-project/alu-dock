[CmdletBinding()]
param(
  [Parameter(Mandatory = $true)]
  [ValidateSet("Install", "Uninstall")]
  [string]$Action,

  [string]$Source,

  [string]$InstallRoot = (Join-Path $env:LOCALAPPDATA "Alu Dock\app")
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version 2.0

$InstallerScriptPath = $MyInvocation.MyCommand.Path
$InstallRoot = [IO.Path]::GetFullPath($InstallRoot).TrimEnd('\')
$PackageMarker = "@REM Generated by Alu Dock Windows package; do not edit in place."
$LegacyLauncherMarker = "@REM Generated by Alu Dock local install; do not edit in place."
$ProductRoot = Split-Path -Parent $InstallRoot
$NextRoot = "$InstallRoot.next"
$PreviousRoot = "$InstallRoot.previous"
$InstallJournal = Join-Path $ProductRoot "install-transaction.json"
$BinRoot = Join-Path $ProductRoot "bin"
$GlobalLauncher = Join-Path $BinRoot "aludock.cmd"
$LegacyLauncher = if ($env:APPDATA) { Join-Path $env:APPDATA "npm\aludock.cmd" } else { $null }
$DesktopExecutable = Join-Path $InstallRoot "AluDock.exe"
$StartMenuShortcut = Join-Path ([Environment]::GetFolderPath("Programs")) "Alu Dock.lnk"
$UninstallRegistry = "HKCU:\Software\Microsoft\Windows\CurrentVersion\Uninstall\AluDock"

function Test-SamePath([string]$Left, [string]$Right) {
  return [string]::Equals(
    [IO.Path]::GetFullPath($Left).TrimEnd('\'),
    [IO.Path]::GetFullPath($Right).TrimEnd('\'),
    [StringComparison]::OrdinalIgnoreCase
  )
}

function Assert-DesktopStopped {
  if (-not (Test-Path -LiteralPath $DesktopExecutable -PathType Leaf)) { return }
  foreach ($process in @(Get-Process -Name "AluDock" -ErrorAction SilentlyContinue)) {
    $path = $null
    try { $path = $process.Path } catch { $path = $null }
    if ($path -and (Test-SamePath $path $DesktopExecutable)) {
      throw "Exit Alu Dock Desktop from its tray menu, then try again."
    }
  }
}

function Invoke-AluDock([string]$Launcher, [string[]]$Arguments) {
  if (-not (Test-Path -LiteralPath $Launcher -PathType Leaf)) {
    throw "The Alu Dock package is incomplete. Extract the complete package and try again."
  }
  $lines = @(& $Launcher @Arguments 2>&1 | ForEach-Object { "$_" })
  $parsed = $null
  foreach ($line in $lines) {
    $trimmed = $line.Trim()
    if (-not $trimmed.StartsWith("{")) { continue }
    try { $parsed = $trimmed | ConvertFrom-Json } catch { }
  }
  if ($LASTEXITCODE -ne 0) {
    $failure = "Alu Dock could not finish this step. Run Setup.cmd again; if it keeps failing, report the message shown in this window."
    if ($parsed -and $parsed.PSObject.Properties["error"] -and $parsed.error.message) {
      $failure = [string]$parsed.error.message
    }
    throw $failure
  }
  return $parsed
}

function Get-FirstLine([string]$Path) {
  if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) { return $null }
  return Get-Content -LiteralPath $Path -TotalCount 1 -ErrorAction Stop
}

function Remove-OwnedLauncher([string]$Path, [string[]]$Markers) {
  if (-not $Path -or -not (Test-Path -LiteralPath $Path -PathType Leaf)) { return $false }
  $firstLine = Get-FirstLine $Path
  if ($Markers -notcontains $firstLine) { return $false }
  Remove-Item -LiteralPath $Path -Force
  return $true
}

function Set-GlobalLauncher {
  New-Item -ItemType Directory -Path $BinRoot -Force | Out-Null
  if (Test-Path -LiteralPath $GlobalLauncher) {
    if ((Get-FirstLine $GlobalLauncher) -ne $PackageMarker) {
      throw "The global aludock command is owned by another file. Move that file and run Setup.cmd again."
    }
  }
  $temporary = "$GlobalLauncher.tmp-$PID"
  $content = @(
    $PackageMarker,
    "@ECHO OFF",
    '@"%LOCALAPPDATA%\Alu Dock\app\aludock.cmd" %*',
    ""
  ) -join "`r`n"
  try {
    [IO.File]::WriteAllText($temporary, $content, [Text.UTF8Encoding]::new($false))
    Move-Item -LiteralPath $temporary -Destination $GlobalLauncher -Force
  } finally {
    Remove-Item -LiteralPath $temporary -Force -ErrorAction SilentlyContinue
  }
  if ($LegacyLauncher) {
    Remove-OwnedLauncher $LegacyLauncher @($LegacyLauncherMarker) | Out-Null
  }
}

function Set-UserPathEntry([string]$Entry, [bool]$Present) {
  $current = [Environment]::GetEnvironmentVariable("Path", "User")
  $parts = @()
  if ($current) {
    $parts = @($current -split ';' | Where-Object { $_.Trim().Length -gt 0 })
  }
  $matching = @($parts | Where-Object { [string]::Equals($_.TrimEnd('\'), $Entry.TrimEnd('\'), [StringComparison]::OrdinalIgnoreCase) })
  if ($Present -and $matching.Count -eq 0) {
    $parts += $Entry
  } elseif (-not $Present -and $matching.Count -gt 0) {
    $parts = @($parts | Where-Object { -not [string]::Equals($_.TrimEnd('\'), $Entry.TrimEnd('\'), [StringComparison]::OrdinalIgnoreCase) })
  } else {
    return
  }
  [Environment]::SetEnvironmentVariable("Path", ($parts -join ';'), "User")
  Send-EnvironmentChanged
}

function Send-EnvironmentChanged {
  if (-not ("AluDockEnvironmentChange" -as [type])) {
    Add-Type -TypeDefinition @"
using System;
using System.Runtime.InteropServices;
public static class AluDockEnvironmentChange {
  [DllImport("user32.dll", CharSet = CharSet.Unicode, SetLastError = true)]
  public static extern IntPtr SendMessageTimeout(
    IntPtr hWnd, uint Msg, UIntPtr wParam, string lParam,
    uint flags, uint timeout, out UIntPtr result);
}
"@
  }
  $result = [UIntPtr]::Zero
  [AluDockEnvironmentChange]::SendMessageTimeout(
    [IntPtr]0xffff, 0x001a, [UIntPtr]::Zero, "Environment", 0x0002, 5000, [ref]$result
  ) | Out-Null
}

function Set-StartMenuShortcut {
  $shell = New-Object -ComObject WScript.Shell
  if (Test-Path -LiteralPath $StartMenuShortcut -PathType Leaf) {
    $existing = $shell.CreateShortcut($StartMenuShortcut)
    if (-not $existing.TargetPath -or -not (Test-SamePath $existing.TargetPath $DesktopExecutable)) {
      throw "The Alu Dock Start Menu name is used by another shortcut. Move that shortcut and run Setup.cmd again."
    }
  }
  $shortcut = $shell.CreateShortcut($StartMenuShortcut)
  $shortcut.TargetPath = $DesktopExecutable
  $shortcut.WorkingDirectory = $InstallRoot
  $shortcut.IconLocation = "$DesktopExecutable,0"
  $shortcut.Save()
}

function Remove-StartMenuShortcut {
  if (-not (Test-Path -LiteralPath $StartMenuShortcut -PathType Leaf)) { return }
  $shell = New-Object -ComObject WScript.Shell
  $shortcut = $shell.CreateShortcut($StartMenuShortcut)
  if ($shortcut.TargetPath -and (Test-SamePath $shortcut.TargetPath $DesktopExecutable)) {
    Remove-Item -LiteralPath $StartMenuShortcut -Force
  }
}

function Set-UninstallRegistration([string]$Version) {
  New-Item -Path $UninstallRegistry -Force | Out-Null
  $command = '"{0}" /D /C ""{1}""' -f (Join-Path $env:SystemRoot "System32\cmd.exe"), (Join-Path $InstallRoot "Uninstall.cmd")
  Set-ItemProperty -Path $UninstallRegistry -Name "DisplayName" -Value "Alu Dock"
  Set-ItemProperty -Path $UninstallRegistry -Name "DisplayVersion" -Value $Version
  Set-ItemProperty -Path $UninstallRegistry -Name "DisplayIcon" -Value "$DesktopExecutable,0"
  Set-ItemProperty -Path $UninstallRegistry -Name "InstallLocation" -Value $InstallRoot
  Set-ItemProperty -Path $UninstallRegistry -Name "UninstallString" -Value $command
  New-ItemProperty -Path $UninstallRegistry -Name "NoModify" -PropertyType DWord -Value 1 -Force | Out-Null
  New-ItemProperty -Path $UninstallRegistry -Name "NoRepair" -PropertyType DWord -Value 1 -Force | Out-Null
}

function Remove-LoginStartup {
  $runKey = "HKCU:\Software\Microsoft\Windows\CurrentVersion\Run"
  if (-not (Test-Path $runKey)) { return }
  $expectedCommand = "$DesktopExecutable --background"
  $properties = (Get-ItemProperty -Path $runKey).PSObject.Properties
  foreach ($property in $properties) {
    if ($property.Name.StartsWith("PS") -or -not ($property.Value -is [string])) { continue }
    if (-not [string]::Equals($property.Value, $expectedCommand, [StringComparison]::OrdinalIgnoreCase)) { continue }
    Remove-ItemProperty -Path $runKey -Name $property.Name -Force
    $approvalKey = "HKCU:\Software\Microsoft\Windows\CurrentVersion\Explorer\StartupApproved\Run"
    if (Test-Path $approvalKey) {
      Remove-ItemProperty -Path $approvalKey -Name $property.Name -Force -ErrorAction SilentlyContinue
    }
  }
}

function Get-PackageManifest([string]$Root) {
  $path = Join-Path $Root "release-manifest.json"
  if (-not (Test-Path -LiteralPath $path -PathType Leaf)) {
    throw "The extracted Alu Dock package is incomplete. Extract the complete ZIP and try again."
  }
  try { return Get-Content -LiteralPath $path -Raw | ConvertFrom-Json }
  catch { throw "The extracted Alu Dock package has an unreadable release manifest. Extract it again and retry." }
}

function Assert-AppComplete([string]$Root) {
  foreach ($required in @("AluDock.exe", "aludock.cmd", "Uninstall.cmd", "release-manifest.json", "dock\dist\src\cli.js")) {
    if (-not (Test-Path -LiteralPath (Join-Path $Root $required) -PathType Leaf)) {
      throw "Alu Dock could not find a complete installed version to update. Run Setup.cmd from a complete Windows package first."
    }
  }
}

function Assert-SystemNode([string]$Launcher) {
  $lines = @(& $Launcher help 2>&1 | ForEach-Object { "$_" })
  if ($LASTEXITCODE -eq 0) { return }
  $message = ($lines | Where-Object { $_.Trim().Length -gt 0 } | Select-Object -First 3) -join " "
  if (-not $message) {
    $message = "Alu Dock needs a current Node.js installation. Install it from https://nodejs.org/ and run Setup.cmd again."
  }
  throw $message
}

function Assert-IntegrationAvailable {
  if ((Test-Path -LiteralPath $GlobalLauncher -PathType Leaf) -and (Get-FirstLine $GlobalLauncher) -ne $PackageMarker) {
    throw "The global aludock command is owned by another file. Move that file and run Setup.cmd again."
  }
  if (Test-Path -LiteralPath $StartMenuShortcut -PathType Leaf) {
    $shell = New-Object -ComObject WScript.Shell
    $shortcut = $shell.CreateShortcut($StartMenuShortcut)
    if (-not $shortcut.TargetPath -or -not (Test-SamePath $shortcut.TargetPath $DesktopExecutable)) {
      throw "The Alu Dock Start Menu name is used by another shortcut. Move that shortcut and run Setup.cmd again."
    }
  }
}

function Copy-PackageTree([string]$From, [string]$To) {
  New-Item -ItemType Directory -Path $To -Force | Out-Null
  & "$env:SystemRoot\System32\robocopy.exe" $From $To /MIR /R:2 /W:1 /NFL /NDL /NJH /NJS /NP | Out-Null
  if ($LASTEXITCODE -ge 8) {
    throw "Alu Dock could not copy the package. Keep the extracted files and try again."
  }
}

function Remove-AppTree([string]$Path) {
  if (-not (Test-Path -LiteralPath $Path)) { return }
  Remove-Item -LiteralPath $Path -Recurse -Force
  if (Test-Path -LiteralPath $Path) {
    throw "Windows is still using files in $Path. Close Alu Dock and run Setup.cmd again."
  }
}

function Write-InstallJournal([bool]$HadPrevious, [string]$PreviousVersion, [string]$Phase = "switching") {
  New-Item -ItemType Directory -Path $ProductRoot -Force | Out-Null
  $temporary = "$InstallJournal.tmp-$PID"
  $record = @{ schemaVersion = 1; phase = $Phase; hadPrevious = $HadPrevious; previousVersion = $PreviousVersion } | ConvertTo-Json -Compress
  try {
    [IO.File]::WriteAllText($temporary, $record, [Text.UTF8Encoding]::new($false))
    Move-Item -LiteralPath $temporary -Destination $InstallJournal -Force
  } finally {
    Remove-Item -LiteralPath $temporary -Force -ErrorAction SilentlyContinue
  }
}

function Complete-InstalledPackage([string]$Version) {
  Write-Host "Starting the Alu Dock service..."
  $serviceSetup = Join-Path $InstallRoot ".windows-host"
  $arguments = if (Test-Path -LiteralPath $serviceSetup -PathType Leaf) {
    @("service", "start", "--json")
  } else {
    @("service", "install", "--now", "--json")
  }
  $service = Invoke-AluDock (Join-Path $InstallRoot "aludock.cmd") $arguments
  if (-not ($service -and $service.ready)) {
    $logs = Join-Path $ProductRoot "logs\host.log"
    throw "Alu Dock did not become ready. Check the log at $logs and run Setup.cmd again."
  }
  Set-GlobalLauncher
  Set-UserPathEntry $BinRoot $true
  Set-StartMenuShortcut
  Set-UninstallRegistration $Version
}

function Remove-InstalledIntegration {
  Remove-StartMenuShortcut
  Remove-Item -LiteralPath $UninstallRegistry -Recurse -Force -ErrorAction SilentlyContinue
  Remove-OwnedLauncher $GlobalLauncher @($PackageMarker) | Out-Null
  Set-UserPathEntry $BinRoot $false
}

function Stop-ServiceForInstall([string]$FallbackLauncher) {
  $launcher = Join-Path $InstallRoot "aludock.cmd"
  if (-not (Test-Path -LiteralPath $launcher -PathType Leaf)) { $launcher = $FallbackLauncher }
  Write-Host "Stopping any running Alu Dock service..."
  Invoke-AluDock $launcher @("service", "stop", "--json") | Out-Null
}

function Recover-InterruptedInstall {
  $hasPrevious = Test-Path -LiteralPath $PreviousRoot -PathType Container
  $hasJournal = Test-Path -LiteralPath $InstallJournal -PathType Leaf
  if (-not $hasPrevious -and -not $hasJournal) {
    Remove-Item -LiteralPath $NextRoot -Recurse -Force -ErrorAction SilentlyContinue
    return
  }

  $journal = $null
  if ($hasJournal) {
    try { $journal = Get-Content -LiteralPath $InstallJournal -Raw | ConvertFrom-Json }
    catch { $journal = $null }
  }
  $journalPhase = ""
  $journalHadPrevious = $true
  if ($journal -and $null -ne $journal.PSObject.Properties["phase"]) {
    $journalPhase = [string]$journal.phase
  }
  if ($journal -and $null -ne $journal.PSObject.Properties["hadPrevious"]) {
    $journalHadPrevious = [bool]$journal.hadPrevious
  }
  if ($journalPhase -eq "committed" -and $null -ne (Get-InstalledVersion)) {
    Write-Host "Finishing the previous Alu Dock setup..."
    Complete-InstalledPackage ([string]((Get-PackageManifest $InstallRoot).productVersion))
    Remove-AppTree $PreviousRoot
    Remove-Item -LiteralPath $NextRoot -Recurse -Force -ErrorAction SilentlyContinue
    Remove-Item -LiteralPath $InstallJournal -Force
    return
  }

  Write-Host "Restoring the previous Alu Dock installation..."
  $launcher = Join-Path $InstallRoot "aludock.cmd"
  if (Test-Path -LiteralPath $launcher -PathType Leaf) {
    try {
      Invoke-AluDock $launcher @("service", "stop", "--json") | Out-Null
    } catch {
      $previousLauncher = Join-Path $PreviousRoot "aludock.cmd"
      if (-not $hasPrevious -or -not (Test-Path -LiteralPath $previousLauncher -PathType Leaf)) { throw }
      Invoke-AluDock $previousLauncher @("service", "stop", "--json") | Out-Null
    }
  }
  if ($hasPrevious) {
    Remove-AppTree $InstallRoot
    Move-Item -LiteralPath $PreviousRoot -Destination $InstallRoot
  } elseif ($journal -and -not $journalHadPrevious) {
    Remove-AppTree $InstallRoot
  }
  Remove-Item -LiteralPath $NextRoot -Recurse -Force -ErrorAction SilentlyContinue
  Remove-Item -LiteralPath $InstallJournal -Force -ErrorAction SilentlyContinue
  if (Test-Path -LiteralPath $InstallRoot -PathType Container) {
    Assert-AppComplete $InstallRoot
    Complete-InstalledPackage ([string]((Get-PackageManifest $InstallRoot).productVersion))
  } else {
    Remove-InstalledIntegration
  }
}

function Stage-Package {
  Remove-Item -LiteralPath $NextRoot -Recurse -Force -ErrorAction SilentlyContinue
  Copy-PackageTree $Source $NextRoot
  Assert-AppComplete $NextRoot
}

function Rollback-Install([bool]$HadPrevious, [string]$PreviousVersion) {
  $stopped = $false
  $stopFailure = ""
  foreach ($launcher in @((Join-Path $InstallRoot "aludock.cmd"), (Join-Path $PreviousRoot "aludock.cmd"))) {
    if (-not (Test-Path -LiteralPath $launcher -PathType Leaf)) { continue }
    try {
      Invoke-AluDock $launcher @("service", "stop", "--json") | Out-Null
      $stopped = $true
      break
    } catch {
      $stopFailure = $_.Exception.Message
    }
  }
  if (-not $stopped) {
    throw "The replacement could not be stopped, so Setup left its files in place. $stopFailure"
  }
  if (Test-Path -LiteralPath $PreviousRoot -PathType Container) {
    Remove-AppTree $InstallRoot
    Move-Item -LiteralPath $PreviousRoot -Destination $InstallRoot
  }
  Remove-Item -LiteralPath $NextRoot -Recurse -Force -ErrorAction SilentlyContinue
  if ($HadPrevious) {
    Assert-AppComplete $InstallRoot
    Complete-InstalledPackage $PreviousVersion
  } else {
    Remove-AppTree $InstallRoot
    Remove-InstalledIntegration
  }
  Remove-Item -LiteralPath $InstallJournal -Force -ErrorAction SilentlyContinue
}

function Start-InstalledDesktop {
  try { Start-Process -FilePath $DesktopExecutable }
  catch { Write-Warning "Alu Dock is ready, but Windows could not open it. Open Alu Dock from the Start Menu." }
}

function Install-Package {
  if (-not $Source) { throw "Setup.cmd must provide the extracted package directory." }
  $Source = [IO.Path]::GetFullPath($Source)
  $sourceManifest = Get-PackageManifest $Source
  $sourceRequired = @("AluDock.exe", "aludock.cmd", "Uninstall.cmd", "release-manifest.json", "LICENSE-APACHE", "dock\dist\src\cli.js", "support\windows-package.ps1")
  foreach ($required in $sourceRequired) {
    if (-not (Test-Path -LiteralPath (Join-Path $Source $required) -PathType Leaf)) {
      throw "The extracted Alu Dock package is incomplete. Extract the complete ZIP and try again."
    }
  }
  $sourceVersion = [string]$sourceManifest.productVersion
  if (-not $sourceVersion) { throw "The extracted Alu Dock package does not identify its version." }

  Assert-DesktopStopped
  Assert-IntegrationAvailable
  Recover-InterruptedInstall
  Assert-SystemNode (Join-Path $Source "aludock.cmd")

  $installedVersion = Get-InstalledVersion
  Write-Host "Copying Alu Dock $sourceVersion into place. This can take a minute..."
  Stage-Package
  $hadPrevious = $null -ne $installedVersion
  $previousVersion = if ($hadPrevious) { [string]$installedVersion } else { "" }
  Write-InstallJournal $hadPrevious $previousVersion
  try {
    Stop-ServiceForInstall (Join-Path $Source "aludock.cmd")
  } catch {
    Remove-Item -LiteralPath $InstallJournal -Force -ErrorAction SilentlyContinue
    Remove-Item -LiteralPath $NextRoot -Recurse -Force -ErrorAction SilentlyContinue
    throw
  }
  try {
    Remove-AppTree $PreviousRoot
    if (Test-Path -LiteralPath $InstallRoot -PathType Container) {
      Move-Item -LiteralPath $InstallRoot -Destination $PreviousRoot
    }
    Move-Item -LiteralPath $NextRoot -Destination $InstallRoot
    Complete-InstalledPackage $sourceVersion
    Write-InstallJournal $hadPrevious $previousVersion "committed"
  } catch {
    $failure = $_.Exception.Message
    try { Rollback-Install $hadPrevious $previousVersion }
    catch { throw "$failure The previous version could not be restored automatically: $($_.Exception.Message) Keep the extracted package and run Setup.cmd again." }
    throw "$failure The previous version has been restored; run Setup.cmd again when you are ready."
  }
  try {
    Remove-AppTree $PreviousRoot
    Remove-Item -LiteralPath $InstallJournal -Force
  } catch {
    Write-Warning "Alu Dock is ready, but Setup could not remove the previous version. Run Setup.cmd again to finish cleanup."
  }
  Start-InstalledDesktop
  Write-Host "Alu Dock $sourceVersion is installed and ready. You can now open it from the Start Menu, and delete the extracted package folder."
}

function Get-InstalledVersion {
  $manifestPath = Join-Path $InstallRoot "release-manifest.json"
  foreach ($required in @("AluDock.exe", "aludock.cmd", "release-manifest.json", "dock\dist\src\cli.js")) {
    if (-not (Test-Path -LiteralPath (Join-Path $InstallRoot $required) -PathType Leaf)) { return $null }
  }
  try {
    $manifest = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json
    return [string]$manifest.productVersion
  } catch {
    return $null
  }
}

function Schedule-PackageCleanup {
  $cleanup = Join-Path $env:TEMP ("AluDock-cleanup-{0}.cmd" -f ([guid]::NewGuid().ToString("N")))
  $commands = @(
    "@ECHO OFF",
    "@PING 127.0.0.1 -n 3 >NUL",
    ('@RMDIR /S /Q "{0}"' -f $InstallRoot),
    ('@RMDIR /S /Q "{0}"' -f $NextRoot),
    ('@RMDIR /S /Q "{0}"' -f $PreviousRoot),
    $(if ($InstallerScriptPath) { '@DEL /F /Q "{0}"' -f $InstallerScriptPath } else { "@REM no temporary script" }),
    '@DEL /F /Q "%~f0"'
  )
  [IO.File]::WriteAllLines($cleanup, $commands, [Text.Encoding]::ASCII)
  Start-Process -FilePath "$env:SystemRoot\System32\cmd.exe" -ArgumentList @("/D", "/C", ('"{0}"' -f $cleanup)) -WindowStyle Hidden
}

function Uninstall-Package {
  Assert-DesktopStopped
  $launcher = Join-Path $InstallRoot "aludock.cmd"
  Invoke-AluDock $launcher @("service", "uninstall", "--json") | Out-Null
  Write-Host "Removing shortcuts and command entries..."
  Remove-LoginStartup
  Remove-StartMenuShortcut
  Remove-Item -LiteralPath $UninstallRegistry -Recurse -Force -ErrorAction SilentlyContinue
  Remove-OwnedLauncher $GlobalLauncher @($PackageMarker) | Out-Null
  if ($LegacyLauncher) {
    Remove-OwnedLauncher $LegacyLauncher @($LegacyLauncherMarker) | Out-Null
  }
  Set-UserPathEntry $BinRoot $false
  if ((Test-Path -LiteralPath $BinRoot -PathType Container) -and @(Get-ChildItem -LiteralPath $BinRoot -Force).Count -eq 0) {
    Remove-Item -LiteralPath $BinRoot -Force
  }
  Schedule-PackageCleanup
  Write-Host "Alu Dock is uninstalled. Your settings remain available for a future installation."
}

if ($Action -eq "Install") {
  Install-Package
} else {
  Uninstall-Package
}
