[CmdletBinding()]
param(
  [Parameter(Mandatory = $true)]
  [ValidateSet("Prepare", "Commit", "Cleanup", "PathInstall", "PathRemove", "Remove")]
  [string]$Action,

  [string]$Source,

  [string]$InstallRoot = (Join-Path $env:LOCALAPPDATA "Alu Dock\app")
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version 2.0

$InstallRoot = [IO.Path]::GetFullPath($InstallRoot).TrimEnd('\')
$PackageMarker = "@REM Generated by Alu Dock Windows package; do not edit in place."
$LegacyLauncherMarker = "@REM Generated by Alu Dock local install; do not edit in place."
$ProductRoot = Split-Path -Parent $InstallRoot
$NextRoot = "$InstallRoot.next"
$PreviousRoot = "$InstallRoot.previous"
$InstallJournal = Join-Path $ProductRoot "install-transaction.json"
$BinRoot = Join-Path $ProductRoot "bin"
$GlobalLauncher = Join-Path $BinRoot "aludock.cmd"
$LegacyLauncher = if ($env:APPDATA) { Join-Path $env:APPDATA "npm\aludock.cmd" } else { $null }
$DesktopExecutable = Join-Path $InstallRoot "AluDock.exe"
$StartMenuShortcut = Join-Path ([Environment]::GetFolderPath("Programs")) "Alu Dock.lnk"
$UninstallRegistry = "HKCU:\Software\Microsoft\Windows\CurrentVersion\Uninstall\AluDock"

function Test-SamePath([string]$Left, [string]$Right) {
  return [string]::Equals(
    [IO.Path]::GetFullPath($Left).TrimEnd('\'),
    [IO.Path]::GetFullPath($Right).TrimEnd('\'),
    [StringComparison]::OrdinalIgnoreCase
  )
}


function Assert-DesktopStopped {
  foreach ($process in @(Get-Process -Name "AluDock" -ErrorAction SilentlyContinue)) {
    $path = $null
    try { $path = $process.Path } catch { $path = $null }
    if (-not $path) {
      # A 32-bit installer can inspect a 64-bit Desktop through CIM even when
      # Process.MainModule is unavailable. Don't silently skip a live Desktop.
      $observed = Get-CimInstance Win32_Process -Filter "ProcessId=$($process.Id)"
      if (-not $observed) { continue }
      $path = $observed.ExecutablePath
      if (-not $path) { throw 'Windows could not check an Alu Dock process. Close Alu Dock Desktop and retry Setup.exe.' }
    }
    if (Test-SamePath $path $DesktopExecutable) {
      throw "Exit Alu Dock Desktop from its tray menu, then try again."
    }
  }
}


function Invoke-AluDock([string]$Launcher, [string[]]$Arguments) {
  if (-not (Test-Path -LiteralPath $Launcher -PathType Leaf)) {
    throw "The Alu Dock package is incomplete. Extract the complete package and try again."
  }
  $lines = @(& $Launcher @Arguments 2>&1 | ForEach-Object { "$_" })
  $parsed = $null
  foreach ($line in $lines) {
    $trimmed = $line.Trim()
    if (-not $trimmed.StartsWith("{")) { continue }
    try { $parsed = $trimmed | ConvertFrom-Json } catch { }
  }
  if ($LASTEXITCODE -ne 0) {
    $failure = "Alu Dock could not finish this step. Run Setup.exe again; if it keeps failing, report the message shown in this window."
    if ($parsed -and $parsed.PSObject.Properties["error"] -and $parsed.error.message) {
      $failure = [string]$parsed.error.message
    }
    throw $failure
  }
  return $parsed
}


function Get-FirstLine([string]$Path) {
  if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) { return $null }
  return Get-Content -LiteralPath $Path -TotalCount 1 -ErrorAction Stop
}


function Remove-OwnedLauncher([string]$Path, [string[]]$Markers) {
  if (-not $Path -or -not (Test-Path -LiteralPath $Path -PathType Leaf)) { return $false }
  $firstLine = Get-FirstLine $Path
  if ($Markers -notcontains $firstLine) { return $false }
  Remove-Item -LiteralPath $Path -Force
  return $true
}


function Set-GlobalLauncher {
  New-Item -ItemType Directory -Path $BinRoot -Force | Out-Null
  if (Test-Path -LiteralPath $GlobalLauncher) {
    if ((Get-FirstLine $GlobalLauncher) -ne $PackageMarker) {
      throw "The global aludock command is owned by another file. Move that file and run Setup.exe again."
    }
  }
  $temporary = "$GlobalLauncher.tmp-$PID"
  $content = @(
    $PackageMarker,
    "@ECHO OFF",
    '@"%LOCALAPPDATA%\Alu Dock\app\aludock.cmd" %*',
    ""
  ) -join "`r`n"
  try {
    [IO.File]::WriteAllText($temporary, $content, [Text.UTF8Encoding]::new($false))
    Move-Item -LiteralPath $temporary -Destination $GlobalLauncher -Force
  } finally {
    Remove-Item -LiteralPath $temporary -Force -ErrorAction SilentlyContinue
  }
  if ($LegacyLauncher) {
    Remove-OwnedLauncher $LegacyLauncher @($LegacyLauncherMarker) | Out-Null
  }
}


function Set-UserPathEntry([string]$Entry, [bool]$Present) {
  $current = [Environment]::GetEnvironmentVariable("Path", "User")
  $parts = @()
  if ($current) {
    $parts = @($current -split ';' | Where-Object { $_.Trim().Length -gt 0 })
  }
  $matching = @($parts | Where-Object { [string]::Equals($_.TrimEnd('\'), $Entry.TrimEnd('\'), [StringComparison]::OrdinalIgnoreCase) })
  if ($Present -and $matching.Count -eq 0) {
    $parts += $Entry
  } elseif (-not $Present -and $matching.Count -gt 0) {
    $parts = @($parts | Where-Object { -not [string]::Equals($_.TrimEnd('\'), $Entry.TrimEnd('\'), [StringComparison]::OrdinalIgnoreCase) })
  } else {
    return
  }
  [Environment]::SetEnvironmentVariable("Path", ($parts -join ';'), "User")
  Send-EnvironmentChanged
}


function Send-EnvironmentChanged {
  if (-not ("AluDockEnvironmentChange" -as [type])) {
    Add-Type -TypeDefinition @"
using System;
using System.Runtime.InteropServices;
public static class AluDockEnvironmentChange {
  [DllImport("user32.dll", CharSet = CharSet.Unicode, SetLastError = true)]
  public static extern IntPtr SendMessageTimeout(
    IntPtr hWnd, uint Msg, UIntPtr wParam, string lParam,
    uint flags, uint timeout, out UIntPtr result);
}
"@
  }
  $result = [UIntPtr]::Zero
  [AluDockEnvironmentChange]::SendMessageTimeout(
    [IntPtr]0xffff, 0x001a, [UIntPtr]::Zero, "Environment", 0x0002, 5000, [ref]$result
  ) | Out-Null
}


function Remove-LoginStartup {
  $runKey = "HKCU:\Software\Microsoft\Windows\CurrentVersion\Run"
  if (-not (Test-Path $runKey)) { return }
  $expectedCommand = "$DesktopExecutable --background"
  $properties = (Get-ItemProperty -Path $runKey).PSObject.Properties
  foreach ($property in $properties) {
    if ($property.Name.StartsWith("PS") -or -not ($property.Value -is [string])) { continue }
    if (-not [string]::Equals($property.Value, $expectedCommand, [StringComparison]::OrdinalIgnoreCase)) { continue }
    Remove-ItemProperty -Path $runKey -Name $property.Name -Force
    $approvalKey = "HKCU:\Software\Microsoft\Windows\CurrentVersion\Explorer\StartupApproved\Run"
    if (Test-Path $approvalKey) {
      Remove-ItemProperty -Path $approvalKey -Name $property.Name -Force -ErrorAction SilentlyContinue
    }
  }
}


function Get-PackageManifest([string]$Root) {
  $path = Join-Path $Root "release-manifest.json"
  if (-not (Test-Path -LiteralPath $path -PathType Leaf)) {
    throw "The extracted Alu Dock package is incomplete. Run Setup.exe again and try again."
  }
  try { return Get-Content -LiteralPath $path -Raw | ConvertFrom-Json }
  catch { throw "The extracted Alu Dock package has an unreadable release manifest. Extract it again and retry." }
}


function Assert-AppComplete([string]$Root) {
  foreach ($required in @("AluDock.exe", "aludock.cmd", "release-manifest.json", "dock\dist\src\cli.js")) {
    if (-not (Test-Path -LiteralPath (Join-Path $Root $required) -PathType Leaf)) {
      throw "Alu Dock could not find a complete installed version to update. Run Setup.exe from a complete Windows package first."
    }
  }
}


function Assert-SystemNode([string]$Launcher) {
  $lines = @(& $Launcher help 2>&1 | ForEach-Object { "$_" })
  if ($LASTEXITCODE -eq 0) { return }
  $message = ($lines | Where-Object { $_.Trim().Length -gt 0 } | Select-Object -First 3) -join " "
  if (-not $message) {
    $message = "Alu Dock needs a current Node.js installation. Install it from https://nodejs.org/ and run Setup.exe again."
  }
  throw $message
}


function Assert-IntegrationAvailable {
  $registration = Get-ItemProperty -LiteralPath $UninstallRegistry -ErrorAction SilentlyContinue
  if ($registration -and $registration.PSObject.Properties['InstallLocation'] -and
      -not (Test-SamePath $registration.InstallLocation $InstallRoot)) {
    throw 'The Windows app registration points to another folder. Keep both folders and contact support before installing.'
  }
  if ((Test-Path -LiteralPath $GlobalLauncher -PathType Leaf) -and (Get-FirstLine $GlobalLauncher) -ne $PackageMarker) {
    throw "The global aludock command is owned by another file. Move that file and run Setup.exe again."
  }
  if (Test-Path -LiteralPath $StartMenuShortcut -PathType Leaf) {
    $shell = New-Object -ComObject WScript.Shell
    $shortcut = $shell.CreateShortcut($StartMenuShortcut)
    if (-not $shortcut.TargetPath -or -not (Test-SamePath $shortcut.TargetPath $DesktopExecutable)) {
      throw "The Alu Dock Start Menu name is used by another shortcut. Move that shortcut and run Setup.exe again."
    }
  }
}


function Copy-PackageTree([string]$From, [string]$To) {
  New-Item -ItemType Directory -Path $To -Force | Out-Null
  & "$env:SystemRoot\System32\robocopy.exe" $From $To /MIR /R:2 /W:1 /NFL /NDL /NJH /NJS /NP | Out-Null
  if ($LASTEXITCODE -ge 8) {
    throw "Alu Dock could not copy the package. Keep the extracted files and try again."
  }
}


function Remove-AppTree([string]$Path) {
  if (-not (Test-Path -LiteralPath $Path)) { return }
  Remove-Item -LiteralPath $Path -Recurse -Force
  if (Test-Path -LiteralPath $Path) {
    throw "Windows is still using files in $Path. Close Alu Dock and run Setup.exe again."
  }
}


function Write-InstallJournal([bool]$HadPrevious, [string]$PreviousVersion, [string]$Phase = "switching") {
  New-Item -ItemType Directory -Path $ProductRoot -Force | Out-Null
  $temporary = "$InstallJournal.tmp-$PID"
  $record = @{ schemaVersion = 1; phase = $Phase; hadPrevious = $HadPrevious; previousVersion = $PreviousVersion } | ConvertTo-Json -Compress
  try {
    [IO.File]::WriteAllText($temporary, $record, [Text.UTF8Encoding]::new($false))
    Move-Item -LiteralPath $temporary -Destination $InstallJournal -Force
  } finally {
    Remove-Item -LiteralPath $temporary -Force -ErrorAction SilentlyContinue
  }
}

# Private Setup primitives. NSIS owns the gate, ordering, registration and UI.
# Never execute a registered legacy UninstallString: ZIP uninstall schedules deletion.
$RetainedRoot = "$InstallRoot.retained"

function Assert-Source([string]$Root = $Source) {
  Assert-AppComplete $Root
  if (-not (Test-Path -LiteralPath (Join-Path $Root 'Uninstall.exe'))) { throw 'The Setup uninstaller is missing. Download Setup.exe again.' }
  $manifest = Get-PackageManifest $Root
  if ($manifest.target -ne 'x86_64-pc-windows-msvc' -or -not $manifest.files) {
    throw 'The Setup payload is incomplete. Download Setup.exe again.'
  }
  foreach ($file in $manifest.files) {
    $path = [IO.Path]::GetFullPath((Join-Path $Root $file.path))
    if (-not $path.StartsWith(([IO.Path]::GetFullPath($Root).TrimEnd('\') + '\'), [StringComparison]::OrdinalIgnoreCase)) {
      throw 'The Setup payload has an invalid file path. Download Setup.exe again.'
    }
    if ((Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash -ne $file.sha256) {
      throw 'The Setup payload is damaged. Download Setup.exe again.'
    }
  }
  Assert-SystemNode (Join-Path $Root 'aludock.cmd')
}

function Protect-LegacyEntrypoints([string]$Root = $InstallRoot) {
  $GuardRoot = Join-Path $Root '.setup-entrypoints'
  if (-not (Test-Path -LiteralPath $Root)) { return }
  # A manifest or this installer's exact old launcher marker establishes ownership.
  $manifest = $null
  try { $manifest = Get-PackageManifest $Root } catch {}
  $owned = $manifest -and $manifest.PSObject.Properties['desktop'] -and $manifest.PSObject.Properties['cli'] -and $manifest.desktop -eq 'AluDock.exe' -and $manifest.cli -eq 'aludock.cmd'
  if (-not $owned) {
    $registration = Get-ItemProperty -LiteralPath $UninstallRegistry -ErrorAction SilentlyContinue
    $owned = $registration -and $registration.PSObject.Properties['InstallLocation'] -and
      (Test-SamePath $registration.InstallLocation $Root) -and
      (Get-FirstLine (Join-Path $Root 'aludock.cmd')) -eq '@REM Generated by Alu Dock package; do not edit in place.'
  }
  if (-not $owned -and -not (Test-Path -LiteralPath $GuardRoot)) {
    throw 'The existing app folder could not be identified. Keep it in place and contact support before installing.'
  }
  # New packages already have native/CLI gate-aware entrypoints.
  if ($manifest -and $manifest.PSObject.Properties['schemaVersion'] -and $manifest.schemaVersion -eq 2 -and -not (Test-Path -LiteralPath $GuardRoot)) { return }
  New-Item -ItemType Directory -Path $GuardRoot -Force | Out-Null
  foreach ($name in @('aludock.cmd', 'AluDock.exe')) {
    $path = Join-Path $Root $name
    $backup = Join-Path $GuardRoot $name
    if (-not (Test-Path -LiteralPath $backup)) {
      if (-not (Test-Path -LiteralPath $path)) { continue }
      # Copy first: interruption never loses the original entrypoint.
      Copy-Item -LiteralPath $path -Destination $backup
    }
    if ($name -eq 'aludock.cmd') {
      [IO.File]::WriteAllText($path, "@ECHO OFF`r`n@ECHO Alu Dock setup is in progress. Run Setup.exe to finish.`r`n@EXIT /B 1`r`n", [Text.Encoding]::ASCII)
    } else {
      Copy-Item -LiteralPath (Join-Path $Source $name) -Destination $path -Force
    }
  }
}

function Restore-Entrypoints([string]$Root) {
  $GuardRoot = Join-Path $Root '.setup-entrypoints'
  if (-not (Test-Path -LiteralPath $GuardRoot)) { return }
  foreach ($name in @('aludock.cmd', 'AluDock.exe')) {
    $backup = Join-Path $GuardRoot $name
    if (Test-Path -LiteralPath $backup) { Copy-Item -LiteralPath $backup -Destination (Join-Path $Root $name) -Force }
  }
  Remove-AppTree $GuardRoot
}

function Assert-PackageDataSafe {
  $launcher = if ($Source) { Join-Path $Source 'aludock.cmd' } else { Join-Path $InstallRoot 'aludock.cmd' }
  # The incoming/installed CLI reads the canonical Host setting. Do not parse a
  # second storage schema here or move the user's store during installation.
  $state = Invoke-AluDock $launcher @('service', 'status', '--json')
  if (-not $state -or -not $state.PSObject.Properties['attachmentDirectory'] -or
      -not $state.PSObject.Properties['stateDirectory']) {
    throw 'The attachment location could not be checked. Keep the current installation and retry Setup.exe.'
  }
  $store = [IO.Path]::GetFullPath([string]$state.attachmentDirectory).TrimEnd('\')
  foreach ($tree in @($InstallRoot, $NextRoot, $PreviousRoot, $RetainedRoot)) {
    $canonical = Join-Path ([string]$state.stateDirectory) (Split-Path -Leaf $tree)
    $entry = Get-Item -LiteralPath $tree -Force -ErrorAction SilentlyContinue
    if ($entry -and ($entry.Attributes -band [IO.FileAttributes]::ReparsePoint)) {
      throw "The app folder is a directory link: $tree. Keep it in place and contact support before changing the installation."
    }
    if ((Test-SamePath $store $canonical) -or $store.StartsWith(($canonical.TrimEnd('\') + '\'), [StringComparison]::OrdinalIgnoreCase)) {
      throw "Attachments are stored inside the program folder: $store. Move the complete attachment store outside that folder using Alu Dock's storage settings procedure, then retry."
    }
  }
  return $state
}

function Get-LegacyProcesses {
  $sid = [Security.Principal.WindowsIdentity]::GetCurrent().User.Value
  $paths = @($InstallRoot, $PreviousRoot, $RetainedRoot) | ForEach-Object { $_.TrimEnd('\') + '\' }
  $processes = @(Get-CimInstance Win32_Process)
  # NSIS's relocated uninstaller can mention the original app path. Never wait
  # for this helper's own parent installer to exit while that parent awaits us.
  $ancestors = [Collections.Generic.HashSet[uint32]]::new()
  $ancestor = [uint32]$PID
  while ($ancestor -gt 0 -and $ancestors.Add($ancestor)) {
    $parent = $processes | Where-Object { $_.ProcessId -eq $ancestor } | Select-Object -First 1
    if (-not $parent) { break }
    $ancestor = [uint32]$parent.ParentProcessId
  }
  foreach ($process in $processes) {
    if ($ancestors.Contains([uint32]$process.ProcessId)) { continue }
    $command = [string]$process.CommandLine
    $executable = [string]$process.ExecutablePath
    $matches = $false
    foreach ($root in $paths) {
      if ($executable.StartsWith($root, [StringComparison]::OrdinalIgnoreCase) -or
          $command.IndexOf($root, [StringComparison]::OrdinalIgnoreCase) -ge 0) { $matches = $true }
    }
    # Unreadable unrelated processes are not evidence of an Alu Dock owner.
    if (-not $matches) { continue }
    $owner = Invoke-CimMethod -InputObject $process -MethodName GetOwnerSid
    if ($owner.ReturnValue -ne 0) { throw 'A process using the Alu Dock package could not be checked. Close its terminal and retry Setup.exe.' }
    if ($owner.Sid -eq $sid) { $process }
  }
}

function Stop-ForReplacement {
  Assert-DesktopStopped
  # Guards close ordinary entrypoints. Already-created old CLI/cmd spawners
  # must exit before the Host snapshot/stop can establish quiescence.
  $launcher = if ($Source) { Join-Path $Source 'aludock.cmd' } else { Join-Path $InstallRoot 'aludock.cmd' }
  $observed = Invoke-AluDock $launcher @('service','status','--json')
  $candidates = @(Get-LegacyProcesses)
  $runtimePids = [Collections.Generic.HashSet[uint32]]::new()
  foreach ($candidate in $candidates) {
    $command = [string]$candidate.CommandLine
    if ($candidate.ProcessId -eq $observed.mainPid -or
        $command -match '(?i)cli\.js"?\s+host(?:\s|$)' -or $command -match 'windows-host-bootstrap\.js') {
      $runtimePids.Add([uint32]$candidate.ProcessId) | Out-Null
    }
  }
  do {
    $expanded = $false
    foreach ($candidate in $candidates) {
      if ($runtimePids.Contains([uint32]$candidate.ParentProcessId) -and $runtimePids.Add([uint32]$candidate.ProcessId)) { $expanded = $true }
    }
  } while ($expanded)
  foreach ($candidate in $candidates) {
    # Workers and their tools are stopped by the Host. Waiting for idle Workers
    # here would prevent every update with an open Work from ever reaching stop.
    if ($runtimePids.Contains([uint32]$candidate.ProcessId)) { continue }
    try { Wait-Process -Id $candidate.ProcessId -Timeout 30 -ErrorAction Stop }
    catch {
      if (Get-Process -Id $candidate.ProcessId -ErrorAction SilentlyContinue) {
        throw 'An Alu Dock terminal or Desktop is still closing. Close it and retry Setup.exe.'
      }
    }
  }
  $status = Invoke-AluDock $launcher @('service','status','--json')
  if ($status.mainPid -gt 0) {
    # Host refusal is authoritative even when it was launched outside app/.
    Invoke-AluDock $launcher @('service','stop','--json') | Out-Null
  }

  if (@(Get-LegacyProcesses).Count -gt 0) {
    throw 'Alu Dock has not finished stopping. Its files are still in place; retry Setup.exe after it closes.'
  }
}

function Recover-Package {
  $journal = $null
  if (Test-Path -LiteralPath $InstallJournal) {
    try { $journal = Get-Content -LiteralPath $InstallJournal -Raw | ConvertFrom-Json } catch {}
  }
  $phase = if ($journal -and $journal.PSObject.Properties['phase']) { [string]$journal.phase } else { '' }
  if (Test-Path -LiteralPath $PreviousRoot) {
    # Guard in the old tree before restoring its canonical entrypoints. Backups
    # move WITH their package, so a newer executable is never restored into it.
    Protect-LegacyEntrypoints $PreviousRoot
    if ($phase -eq 'switching' -or -not (Test-Path -LiteralPath $InstallRoot)) {
      Remove-AppTree $InstallRoot
      Move-Item -LiteralPath $PreviousRoot -Destination $InstallRoot
    } else {
      # Committed/damaged/legacy missing journals are repair, not permission to
      # delete the only complete fallback. Retain it until the NEW commit.
      if (Test-Path -LiteralPath $RetainedRoot) {
        Assert-AppComplete $RetainedRoot
        Remove-AppTree $PreviousRoot
      } else {
        Move-Item -LiteralPath $PreviousRoot -Destination $RetainedRoot
      }
    }
  }
  Remove-Item -LiteralPath $InstallJournal -Force -ErrorAction SilentlyContinue
}

function Prepare-Package {
  Assert-Source
  $state = Assert-PackageDataSafe
  # Don't temporarily replace launchers used by Work which is already busy.
  # Stop rechecks after the guards, so new work cannot bypass stop protection.
  if ($state.blockingWork -gt 0) { throw 'Work is still active. Finish or stop it before installing Alu Dock.' }
  Assert-IntegrationAvailable
  Assert-DesktopStopped
  try {
    Protect-LegacyEntrypoints
    Stop-ForReplacement
    Recover-Package
    # Recovery may have restored legacy entrypoints; guard that complete version.
    Protect-LegacyEntrypoints
    Remove-AppTree $NextRoot
    Copy-PackageTree $Source $NextRoot
    Assert-Source $NextRoot
    Write-InstallJournal (Test-Path -LiteralPath $InstallRoot) ''
  } catch {
    if (Test-Path -LiteralPath $InstallRoot) { Restore-Entrypoints $InstallRoot }
    throw
  }
}

function Commit-Package {
  try {
    if (Test-Path -LiteralPath $InstallRoot) { Move-Item -LiteralPath $InstallRoot -Destination $PreviousRoot }
    Move-Item -LiteralPath $NextRoot -Destination $InstallRoot
    Write-InstallJournal (Test-Path -LiteralPath $PreviousRoot) '' 'committed'
    # This receipt is written only after guarded, verified process release.
    [IO.File]::WriteAllText((Join-Path $ProductRoot 'host-owner.json'), '{"pid":0,"exited":true}')
    [IO.File]::WriteAllText((Join-Path $InstallRoot '.windows-host'), 'Alu Dock Windows user Host')
  } catch {
    Undo-Package
    throw
  }
}

function Undo-Package {
  if (Test-Path -LiteralPath $InstallJournal) {
    $journal = Get-Content -LiteralPath $InstallJournal -Raw | ConvertFrom-Json
    if ($journal.phase -eq 'committed') { return }
    if (Test-Path -LiteralPath $PreviousRoot) {
      Remove-AppTree $InstallRoot
      Move-Item -LiteralPath $PreviousRoot -Destination $InstallRoot
    }
    if (Test-Path -LiteralPath $InstallRoot) { Restore-Entrypoints $InstallRoot }
    Remove-AppTree $NextRoot
    Remove-Item -LiteralPath $InstallJournal -Force
  }
}

switch ($Action) {
  Prepare { Prepare-Package }
  Commit { Commit-Package }
  Cleanup {
    Assert-PackageDataSafe | Out-Null
    Remove-AppTree $PreviousRoot
    Remove-AppTree $RetainedRoot
    Remove-Item -LiteralPath $InstallJournal -Force -ErrorAction SilentlyContinue
  }
  PathInstall { Set-GlobalLauncher; Set-UserPathEntry $BinRoot $true }
  PathRemove {
    Remove-OwnedLauncher $GlobalLauncher @($PackageMarker) | Out-Null
    if ($LegacyLauncher) { Remove-OwnedLauncher $LegacyLauncher @($LegacyLauncherMarker) | Out-Null }
    Set-UserPathEntry $BinRoot $false
    Remove-LoginStartup
  }
  Remove {
    Assert-PackageDataSafe | Out-Null
    Assert-IntegrationAvailable
    Stop-ForReplacement
    Remove-AppTree $InstallRoot
    Remove-AppTree $NextRoot
    Remove-AppTree $PreviousRoot
    Remove-AppTree $RetainedRoot
  }
}
